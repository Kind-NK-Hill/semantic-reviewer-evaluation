def read(name):
    return [json.loads(s) for s in (ROOT / name).read_text(encoding='utf-8').splitlines()]


def quotient_counterexample():
    # Bitmasks encode subsets. X is the three-point upward-chain topology.
    tx, ty, p = {0, 4, 6, 7}, {0, 3}, (0, 1, 0)
    def preimage(f, subset):
        return sum(1 << i for i, v in enumerate(f) if subset & (1 << v))
    def topology(t, n):
        return 0 in t and (1 << n) - 1 in t and all(
            a & b in t and a | b in t for a in t for b in t)
    assert topology(tx, 3) and topology(ty, 2)
    assert set(p) == {0, 1}
    quotient_opens = {s for s in range(4) if preimage(p, s) in tx}
    assert quotient_opens == ty
    sections = []
    for a in range(3):
        for b in range(3):
            f = (a, b)
            if tuple(p[i] for i in f) == (0, 1):
                bad = [s for s in sorted(tx) if preimage(f, s) not in ty]
                assert bad
                sections.append({'section': list(f), 'open_sets_with_nonopen_preimage': bad})
    assert len(sections) == 2
    return {'item': 'cc_0790', 'X_open_masks': sorted(tx), 'Y_open_masks': sorted(ty),
            'p': list(p), 'quotient': True, 'all_sections': sections,
            'continuous_sections': 0}


def compute():
    items = read('data/processed/items.jsonl')
    records = read('data/judgments.jsonl')
    reviews = read('labels/technical-review.jsonl')
    queue = json.loads((ROOT / 'results/post_review.json').read_text(encoding='utf-8'))
    assert len(reviews) == 74 and len({r['id'] for r in reviews}) == 74
    assert {r['id'] for r in reviews} == {r['id'] for r in queue['priority_review']['items']}
    by_id = {r['id']: r for r in reviews}
    original = np.array([r['label'] == 'true' for r in items])
    revised = original.copy()
    changed = []
    for i, item in enumerate(items):
        r = by_id.get(item['id'])
        if r and r['decision'] != 'convention':
            assert r['decision'] in ('faithful', 'unfaithful')
            revised[i] = r['decision'] == 'faithful'
            if revised[i] != original[i]:
                changed.append({'id': item['id'], 'published_label': item['label'],
                                'review_label': 'true' if revised[i] else 'false'})
    groups = np.array([r['group'] for r in items])
    assert len(set(groups)) == 858
    settings = json.loads((ROOT / 'protocol/analysis_settings.json').read_text())
    os.environ['RC_BOOTSTRAP_METHOD'] = settings['bootstrap_method']
    os.environ['RC_NONINFERIORITY_COVERAGE'] = str(settings['noninferiority_coverage'])
    result = {'scope': 'post-hoc targeted AI-assisted technical review; not an independent gold set',
              'seed': 20261110, 'draws': 10000,
              'review_counts': dict(Counter(r['decision'] for r in reviews)),
              'changes': changed,
              'changes_by_direction': dict(Counter(r['published_label']+'->'+r['review_label'] for r in changed)),
              'convention_policy': 'Keep all 14 convention/context cases at their published labels.',
              'cc0790_counterexample': quotient_counterexample(), 'scenarios': {}}
    for scenario, labels in [('published', original), ('technical_review', revised)]:
        output = {'faithful': int(labels.sum()), 'unfaithful': int((~labels).sum()), 'models': {}}
        for model in ('terra', 'flash'):
            gen = np.random.default_rng(20261110)
            rs = [r for r in records if r['model'] == model]
            arrays = {c: matrix(rs, items, c, 3) for c in ('R0', 'R1', 'R1g')}
            rates = {}
            for config, a in arrays.items():
                rates[config] = {k: interval(item_rate(a, kind)[mask], groups[mask], 10000, gen)
                                 for k, mask, kind in [('leak', ~labels, 'accept'), ('reject', labels, 'reject')]}
            comparisons = {c: compare(arrays['R1'], arrays[c], labels, groups, 10000, gen)
                           for c in ('R0', 'R1g')}
            output['models'][model] = {
                'rates': rates, 'comparisons': comparisons,
                'rule_replay': final_decision(comparisons['R0']['decision'], comparisons['R1g']['decision'])}
        result['scenarios'][scenario] = output
    # This check ties the new reader to the frozen estimates, independently of bootstrap draw order.
    frozen = json.loads((ROOT / 'results/main_results.json').read_text(encoding='utf-8'))
    for m in ('terra', 'flash'):
        for c in ('R0', 'R1', 'R1g'):
            for metric in ('leak', 'reject'):
                assert abs(result['scenarios']['published']['models'][m]['rates'][c][metric]['estimate'] -
                           frozen['models'][m]['configs'][c][metric]['estimate']) < 1e-12
    unanimous = queue['unanimous_false_labeled']['ids']
    result['unanimous_26_review'] = dict(Counter(by_id[i]['decision'] for i in unanimous))
    return result


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = compute()
    path = ROOT / 'results/label_sensitivity.json'
    if args.check:
        expected = json.loads(path.read_text(encoding='utf-8'))
        from reproduce import compare as assert_equal
        assert_equal(expected, result)
        print('Verified 74 review inputs, label sensitivity, original estimates and finite counterexample.')
    else:
        path.write_text(json.dumps(result, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
        print(json.dumps({k: result[k] for k in ('review_counts', 'changes_by_direction', 'unanimous_26_review')}, ensure_ascii=False))
        for scenario, s in result['scenarios'].items():
            for m, d in s['models'].items():
                print(scenario, m, d['rule_replay'])
                for c, v in d['rates'].items():
                    print(c, {k: round(x['estimate']*100, 4) for k, x in v.items()})


if __name__ == '__main__':
    main()
